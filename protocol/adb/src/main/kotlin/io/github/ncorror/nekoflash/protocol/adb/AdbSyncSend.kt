package io.github.ncorror.nekoflash.protocol.adb

/**
 * Что стало с файлом назначения на устройстве.
 *
 * Отдельно от исхода операции намеренно. «Операция не удалась» и «на устройстве
 * ничего не изменилось» — разные утверждения, и второе почти никогда не следует
 * из первого: устройство может отказать, уже создав или обрезав файл.
 * `03_PROTOCOL_AND_SAFETY_INVARIANTS_RU.md` §7 требует называть такой случай
 * `Unknown`, а не выдавать его за безопасную отмену.
 */
public enum class AdbSyncDestination {
    /**
     * Назначение не могло измениться.
     *
     * Утверждается только когда запрос `SEND` **не покинул хост**: сессия не
     * открыта, путь непредставим, или отправка оборвалась, не отдав в USB ни
     * одного байта.
     */
    UNTOUCHED,

    /** Устройство ответило `OKAY`: файл записан целиком. */
    COMMITTED,

    /**
     * Доказать состояние назначения нечем.
     *
     * Единственное честное значение после того, как `SEND` ушёл, а `OKAY` не
     * пришёл. Хост не видит, в какой момент `adbd` создаёт и обрезает файл, и
     * не вправе утверждать, что не тронул его.
     */
    UNKNOWN,
}

/**
 * Исход записи файла на устройство.
 *
 * ## Где здесь граница мутации
 *
 * Граница пересекается в момент записи запроса `SEND` в USB — раньше, чем
 * уходит первый блок `DATA`.
 *
 * Это сознательно консервативнее, чем в A2 Sideload, где границей отмечен
 * первый блок payload (`SideloadStreamSession.markPayloadTransmissionStarted`).
 * Разница не в осторожности, а в протоколе: в Sideload устройство **запрашивает**
 * каждый блок, поэтому до первого отданного блока на нём заведомо ничего не
 * менялось. В `sync:` хост называет путь и режим сразу, и дальше устройство
 * действует по одному этому сообщению.
 *
 * ## Это измерено, а не предположено
 *
 * Прогон на `vayu` 2026-09-08 (`07` §6.38) писал 16 МиБ поверх существующего
 * файла в 4 КиБ с известным отпечатком и обрывал передачу выдёргиванием
 * кабеля. После переподключения файла **не стало**: `STAT` вернул нулевой
 * режим, `sha256sum` и `ls` ответили `No such file or directory`.
 *
 * Значит оборванный `SEND` действительно уничтожает то, что лежало по этому
 * пути. Ответ [AdbSyncDestination.UNKNOWN] после границы — не перестраховка, а
 * единственно верное утверждение: сказать «ничего не изменилось» здесь значило
 * бы солгать о результате, что `03_PROTOCOL_AND_SAFETY_INVARIANTS_RU.md` §7
 * запрещает прямо.
 *
 * Чего прогон **не** различает: уничтожен ли файл в момент `SEND` или в момент
 * первого блока `DATA`. К моменту обрыва ушло 64 блока, и оба объяснения
 * подходят. Развести их выдёргиванием кабеля нельзя в принципе — между
 * `SEND` и первым блоком проходят микросекунды. На поведение это не влияет:
 * реальная передача всегда шлёт `DATA` сразу за `SEND`, поэтому обе гипотезы
 * дают один и тот же ответ на единственный вопрос, который тут задаётся.
 *
 * ## Повторная попытка
 *
 * Автоматически повторять `SEND` после [AdbSyncDestination.UNKNOWN] запрещено
 * (`03` §3, §8). Повтор — решение оператора, принимаемое после того, как он
 * увидел настоящее состояние назначения.
 */
public sealed interface AdbSyncSendOutcome {
    /**
     * Сколько байт содержимого ушло в USB.
     *
     * Считаются только блоки, чей кадр записан **целиком**. Блок, на котором
     * запись оборвалась, не засчитывается: сколько его байт успело уйти в
     * провод, хост не знает, а завышать этот счётчик — врать ровно в том поле,
     * ради честности которого весь тип и существует.
     */
    public val bytesSent: Long

    /** Что известно о файле назначения. */
    public val destination: AdbSyncDestination

    /** Устройство подтвердило запись. */
    public data class Committed(
        override val bytesSent: Long,
        /** SHA-256 того, что хост отдал в USB. */
        public val sha256: String,
    ) : AdbSyncSendOutcome {
        override val destination: AdbSyncDestination
            get() = AdbSyncDestination.COMMITTED
    }

    /**
     * Подтверждения нет.
     *
     * [reason] говорит, почему прервалась операция, [destination] — что из
     * этого следует для файла на устройстве. Эти два поля независимы:
     * `DEVICE_REFUSED` вместе с [AdbSyncDestination.UNKNOWN] означает, что
     * устройство честно ответило `FAIL`, но остаток файла оно за собой не
     * убирало.
     */
    public data class Failed(
        public val reason: AdbSyncFailure,
        public val detail: String,
        override val destination: AdbSyncDestination,
        override val bytesSent: Long,
    ) : AdbSyncSendOutcome
}
