package io.github.ncorror.nekoflash.protocol.adb

/**
 * Откуда хост берёт блоки нагрузки.
 *
 * Доступ **произвольный, а не потоковый**, и это не удобство вызывающего.
 * Sideload управляется запросами Recovery, и один и тот же блок оно вправе
 * попросить не раз (`03_PROTOCOL_AND_SAFETY_INVARIANTS_RU.md` §6). Источник,
 * умеющий только «дай следующее», на повторный запрос отдал бы следующий кусок,
 * и образ уехал бы перемешанным — причём передача выглядела бы исправной до
 * самого вердикта Recovery.
 */
public fun interface AdbSideloadSource {
    /**
     * Читает ровно [length] байт, начиная с [offset].
     *
     * Короткое чтение — сбой источника, а не конец нагрузки: длину назвало
     * Recovery исходя из объявленного нами объёма, и отдать меньше значило бы
     * отдать другой блок. Не прочиталось — бросай: [AdbSideloadDriver] превратит
     * это в сбой файла, не тронув границу мутации.
     */
    public fun read(offset: Long, length: Int): ByteArray
}

/**
 * За чем следит вызывающий, пока идёт передача.
 *
 * Два события, и второе не выводится из первого. Прогресс приходит на
 * **подтверждённое** покрытие, то есть уже после того, как блок ушёл; граница
 * мутации проходится раньше — в тот момент, когда первый блок только
 * отправляется. Считать её по первому прогрессу значило бы предлагать отмену
 * там, где отменять уже нечего.
 */
public interface AdbSideloadListener {
    /** Recovery подтвердило блок, и покрытие выросло. */
    public fun onProgress(progress: AdbSideloadProgress) {}

    /**
     * Первый блок нагрузки уходит на провод.
     *
     * После этого отмены не существует: Recovery начинает менять устройство,
     * как только у него появились данные (`03` §6).
     */
    public fun onMutationBoundary() {}

    public companion object {
        /** Никому ничего не рассказывать. */
        public val NOTHING: AdbSideloadListener = object : AdbSideloadListener {}
    }
}
