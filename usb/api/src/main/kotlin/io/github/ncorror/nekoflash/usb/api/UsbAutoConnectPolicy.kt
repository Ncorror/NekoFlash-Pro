package io.github.ncorror.nekoflash.usb.api

/**
 * Можно ли подключаться к интерфейсу без отдельного действия пользователя.
 *
 * Правило перенесено из Legacy, где оно записано прямо в комментарии к
 * attach-фильтру: канонические и совместимые интерфейсы подключаются
 * автоматически, а generic vendor bulk-интерфейс показывается только для
 * ручного выбора.
 *
 * Основание не в удобстве. Захват исключителен: пока интерфейс удерживается,
 * его не получит никто другой на этом хосте. Отобрать устройство у чужого
 * владельца допустимо только тогда, когда мы уверены, что оно наше: у
 * канонических дескрипторов такая уверенность есть, у совпадения по одному
 * лишь классу `0xFF` — нет. Под этот класс попадает и принтер, и
 * измерительный прибор.
 */
public object UsbAutoConnectPolicy {
    /**
     * Разрешено ли автоматическое подключение к такому кандидату.
     *
     * Решение принимается по уверенности классификации, а не по производителю:
     * список знакомых vendorId отсеивал бы устройство за то, что его нет в
     * списке, а не за то, что оно отказало.
     */
    public fun allowsAutomaticConnect(candidate: UsbInterfaceCandidate): Boolean =
        when (candidate.confidence) {
            UsbMatchConfidence.CANONICAL -> true
            UsbMatchConfidence.ANDROID_COMPATIBLE -> true
            UsbMatchConfidence.GENERIC_VENDOR -> false
        }
}
