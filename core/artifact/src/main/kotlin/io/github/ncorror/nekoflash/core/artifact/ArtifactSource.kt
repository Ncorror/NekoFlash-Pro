package io.github.ncorror.nekoflash.core.artifact

import java.io.InputStream

/**
 * Чтение с произвольного места.
 *
 * Нужно там, где принимающая сторона сама выбирает, что просить: Sideload
 * управляется запросами Recovery, и один и тот же блок оно вправе попросить не
 * раз (`03_PROTOCOL_AND_SAFETY_INVARIANTS_RU.md` §6).
 */
fun interface ArtifactRandomAccess {
    /**
     * Читает ровно [length] байт с [offset].
     *
     * Короткое чтение — сбой источника, а не конец: длину назвал вызывающий
     * исходя из объявленного размера, и отдать меньше значит отдать другое.
     */
    fun read(offset: Long, length: Int): ByteArray
}

/**
 * Откуда приложение берёт содержимое, выбранное пользователем.
 *
 * Контракт `06_OPERATIONS_STORAGE_LIFECYCLE_RU.md` §6. Главное в нём — что
 * произвольный доступ **необязателен и не подделывается**: источник, который
 * его не умеет, отвечает `null`, а не выдаёт видимость доступа поверх потока.
 * Подделка была бы худшим из возможных исходов: на повторный запрос блока она
 * отдала бы следующий кусок, и образ уехал бы перемешанным при исправной с виду
 * передаче.
 */
interface ArtifactSource {
    /** Что известно об артефакте на момент открытия. */
    val identity: ArtifactIdentity

    /**
     * Отпечаток на момент **открытия** источника.
     *
     * Хранится, а не считается заново: сравнивать надо с тем, что было при
     * выборе файла, а не с самим собой. Между выбором и нажатием кнопки проходит
     * сколько угодно времени, и ровно этот промежуток проверка и закрывает.
     */
    val openedStamp: ArtifactStamp

    /**
     * Отпечаток **сейчас**.
     *
     * Снимается ещё раз перед мутирующей передачей: между выбором файла и
     * нажатием кнопки проходит сколько угодно времени.
     */
    fun stamp(): ArtifactStamp

    /** Последовательное чтение с начала. Закрывает вызывающий. */
    fun open(): InputStream

    /**
     * Чтение с произвольного места, если источник это умеет.
     *
     * `null` означает «не умею», и это ответ, а не ошибка. Что с этим делать —
     * решает вызывающий: для Sideload единственный законный ход это стажировать
     * источник во временный файл (`ArtifactStaging`).
     */
    fun randomAccess(): ArtifactRandomAccess?
}
