package io.github.ncorror.nekoflash.core.artifact

import java.io.OutputStream

/**
 * Куда приложение кладёт прочитанное с устройства.
 *
 * Контракт `06_OPERATIONS_STORAGE_LIFECYCLE_RU.md` §7. Смысл разделения на
 * [open], [commit] и [abandon] один: **у места назначения не должно оказаться
 * файла, про который никто не доказал, что он целый**. Поэтому пишется во
 * временное место, а на настоящее оно переезжает только после того, как счёт
 * байт сошёлся и поток закрылся без ошибки.
 */
interface ArtifactSink {
    /** Как назвать назначение в сообщении оператору. */
    val destination: String

    /**
     * Умеет ли провайдер атомарную замену.
     *
     * `false` не запрещает запись, но обязан быть виден: без атомарной замены
     * между удалением старого и появлением нового существует момент, когда нет
     * ни того, ни другого, и `06` §7 требует отражать это честно, а не молчать.
     */
    val atomicCommit: Boolean

    /** Открывает временное назначение. Закрывает вызывающий. */
    fun open(): OutputStream

    /**
     * Переводит написанное на настоящее место.
     *
     * Вызывается **только** после доказанного успеха. Ошибка здесь — это ошибка
     * записи, а не мелочь закрытия: `fsync` и `close` сообщают о невынесенных
     * на диск байтах, и проглотить их значило бы объявить целым файл, которого
     * может не быть.
     */
    fun commit(): ArtifactCommit

    /**
     * Убирает временное назначение.
     *
     * Причина называется: оператору важно знать, почему файла нет, а не только
     * что его нет.
     */
    fun abandon(reason: String)
}

/** Чем кончился перевод написанного на настоящее место. */
sealed interface ArtifactCommit {
    /**
     * Файл на месте.
     *
     * [atomic] повторяет `ArtifactSink.atomicCommit` не для красоты: исход
     * операции живёт дольше приёмника, и через сутки в истории должно быть
     * видно, была ли замена атомарной.
     */
    data class Done(val destination: String, val atomic: Boolean) : ArtifactCommit

    /** Перевести не удалось; написанное убрано или названо как оставшееся. */
    data class Failed(val detail: String) : ArtifactCommit
}
