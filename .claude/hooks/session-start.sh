#!/bin/bash
# Готовит облачную сессию к сборке: Android SDK и JDK 17, которых нет в образе.
#
# Тяжёлую установку делает Setup script окружения — он выполняется один раз, и
# дальше файловая система достаётся сессиям снапшотом. Этот хук — страховка:
# Setup script опирается на то, что репозиторий уже склонирован, а документация
# этого не обещает, и при ненайденном скрипте он отчитывается успехом. Хук же
# запускается заведомо при готовом дереве.
#
# На готовой машине стоит около нуля: сам скрипт проверяет наличие до установки.
set -euo pipefail

# Локальную машину не трогаем ни при каких условиях. Скрипт ставит пакеты от
# root и пишет в /opt — на телефоне в Termux или на чужом ноутбуке это не
# страховка, а порча рабочей среды.
if [ "${CLAUDE_CODE_REMOTE:-}" != "true" ]; then
  exit 0
fi

root="${CLAUDE_PROJECT_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
"$root/scripts/dev/provision_android_toolchain.sh"

# Переменные нужны самой сессии, а не только будущим оболочкам: Gradle читает
# их из окружения процесса.
if [ -n "${CLAUDE_ENV_FILE:-}" ]; then
  {
    echo 'export ANDROID_HOME=/opt/android-sdk'
    echo 'export ANDROID_SDK_ROOT=/opt/android-sdk'
  } >> "$CLAUDE_ENV_FILE"
fi
