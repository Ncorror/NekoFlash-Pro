package io.github.ncorror.nekoflash.terminal

import android.content.Context
import android.content.res.AssetManager
import android.os.Build
import android.system.Os
import java.io.File
import java.io.FileOutputStream
import java.io.IOException
import java.io.RandomAccessFile
import java.nio.file.Files
import java.nio.file.StandardCopyOption

/**
 * Installs the packaged aarch64 Starship binary into app-private storage.
 *
 * The current product terminal is an ADB PTY, so this binary is for a future
 * local Android shell only. It must never be sent to the remote device merely
 * because it exists in the APK: the remote ABI and libc are independent.
 * Call [install] from `Dispatchers.IO`.
 */
public class StarshipInstaller(
    context: Context,
    private val assets: AssetManager = context.assets,
) {
    private val root = File(context.filesDir, "terminal")
    private val binDir = File(root, "bin")
    private val homeDir = File(root, "home")
    private val binary = File(binDir, "starship")
    private val profile = File(homeDir, ".bashrc")

    /** Result is explicit so a missing optional asset is not reported as a crash. */
    public sealed interface Result {
        public data class Installed(val binary: File, val profile: File, val localExecAllowed: Boolean) : Result
        public data object MissingAsset : Result
        public data class Failed(val detail: String, val cause: Throwable? = null) : Result
    }

    private val lock = Any()

    /** True when the APK contains one of the supported asset layouts. */
    public fun hasPackagedBinary(): Boolean = findAsset() != null

    /** Copies, validates, chmods and profiles Starship atomically. */
    public fun install(): Result = synchronized(lock) {
        val asset = findAsset() ?: return Result.MissingAsset
        runCatching {
            binDir.mkdirs()
            homeDir.mkdirs()
            require(binDir.isDirectory && homeDir.isDirectory) { "cannot create terminal directories" }

            if (!isAarch64Elf(binary)) {
                copyAssetAtomically(asset)
            }
            require(isAarch64Elf(binary)) { "asset is not an AArch64 ELF executable" }
            makeExecutable(binary)
            writeProfileAtomically()
            Result.Installed(binary, profile, localExecAllowed = Build.VERSION.SDK_INT < Build.VERSION_CODES.Q)
        }.getOrElse { error ->
            Result.Failed(error.message ?: error.javaClass.simpleName, error)
        }
    }

    /**
     * Command line for a local PTY launcher on pre-Android-10 devices.
     *
     * Android 10+ rejects `execve` from the writable app home. A production
     * local PTY must package Starship as executable code (for example through
     * an ABI-specific native-library payload) or run it on the remote device.
     */
    public fun localBashCommand(): List<String> {
        check(Build.VERSION.SDK_INT < Build.VERSION_CODES.Q) {
            "Android 10+ forbids executing Starship from app-private filesDir"
        }
        return listOf("bash", "--rcfile", profile.absolutePath, "-i")
    }

    private fun findAsset(): String? = ASSET_CANDIDATES.firstOrNull { path ->
        try {
            assets.open(path).use { }
            true
        } catch (_: IOException) {
            false
        }
    }

    private fun copyAssetAtomically(asset: String) {
        val temporary = File(binDir, ".starship.tmp-${System.nanoTime()}")
        assets.open(asset).use { input ->
            FileOutputStream(temporary).use { output ->
                input.copyTo(output, COPY_BUFFER_BYTES)
                output.fd.sync()
            }
        }
        try {
            Files.move(
                temporary.toPath(),
                binary.toPath(),
                StandardCopyOption.ATOMIC_MOVE,
                StandardCopyOption.REPLACE_EXISTING,
            )
        } catch (_: java.nio.file.AtomicMoveNotSupportedException) {
            Files.move(temporary.toPath(), binary.toPath(), StandardCopyOption.REPLACE_EXISTING)
        } finally {
            temporary.delete()
        }
    }

    private fun makeExecutable(file: File) {
        // 0755: owner can replace the file, while the shell can execute it.
        runCatching { Os.chmod(file.absolutePath, EXECUTABLE_PERMISSIONS) }
        require(file.setExecutable(true, false)) { "cannot mark Starship executable" }
        file.setReadable(true, false)
        file.setWritable(false, true)
    }

    private fun writeProfileAtomically() {
        val temporary = File(homeDir, ".bashrc.tmp-${System.nanoTime()}")
        val bin = shellQuote(binDir.absolutePath)
        val executable = shellQuote(binary.absolutePath)
        val home = shellQuote(homeDir.absolutePath)
        val text = buildString {
            appendLine("# Generated by NekoFlash; safe to replace on the next install.")
            appendLine("export HOME=$home")
            appendLine("export PATH=$bin:\"${'$'}{PATH:-}\"")
            appendLine("if [ -n \"${'$'}{BASH_VERSION:-}\" ] && [ -x $executable ]; then")
            appendLine("  eval \"${'$'}($executable init bash)\"")
            appendLine("fi")
        }
        FileOutputStream(temporary).use { output ->
            output.write(text.toByteArray(Charsets.UTF_8))
            output.fd.sync()
        }
        try {
            Files.move(
                temporary.toPath(),
                profile.toPath(),
                StandardCopyOption.ATOMIC_MOVE,
                StandardCopyOption.REPLACE_EXISTING,
            )
        } catch (_: java.nio.file.AtomicMoveNotSupportedException) {
            Files.move(temporary.toPath(), profile.toPath(), StandardCopyOption.REPLACE_EXISTING)
        } finally {
            temporary.delete()
        }
    }

    private fun isAarch64Elf(file: File): Boolean {
        if (!file.isFile || file.length() < ELF_HEADER_BYTES) return false
        return runCatching {
            RandomAccessFile(file, "r").use { input ->
                val header = ByteArray(ELF_HEADER_BYTES)
                input.readFully(header)
                header[0] == ELF_MAGIC_FIRST_BYTE.toByte() && header[1] == 'E'.code.toByte() &&
                    header[2] == 'L'.code.toByte() && header[ELF_MAGIC_LAST_OFFSET] == 'F'.code.toByte() &&
                    header[ELF_CLASS_OFFSET].toInt() == ELFCLASS64 &&
                    header[ELF_DATA_OFFSET].toInt() == ELFDATA2LSB &&
                    (header[ELF_MACHINE_OFFSET].toInt() and UNSIGNED_BYTE_MASK) == EM_AARCH64 &&
                    header[ELF_MACHINE_OFFSET + 1].toInt() == 0
            }
        }.getOrDefault(false)
    }

    private fun shellQuote(value: String): String = "'" + value.replace("'", "'\\''") + "'"

    private companion object {
        val ASSET_CANDIDATES = listOf(
            "starship/aarch64/starship",
            "starship/arm64-v8a/starship",
            "starship",
        )
        const val COPY_BUFFER_BYTES = 64 * 1024
        const val ELF_HEADER_BYTES = 20
        const val EXECUTABLE_PERMISSIONS = 0x1ED
        const val ELF_MAGIC_FIRST_BYTE = 0x7F
        const val ELF_MAGIC_LAST_OFFSET = 3
        const val UNSIGNED_BYTE_MASK = 0xFF
        const val ELF_CLASS_OFFSET = 4
        const val ELF_DATA_OFFSET = 5
        const val ELF_MACHINE_OFFSET = 18
        const val ELFCLASS64 = 2
        const val ELFDATA2LSB = 1
        const val EM_AARCH64 = 183
    }
}
